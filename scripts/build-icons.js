#!/usr/bin/env node
/** Bundles the selected Lucide icons into a browser script for the renderer. */
const path = require('path');
const esbuild = require('esbuild');

const root = path.resolve(__dirname, '..');
const outfile = path.join(root, 'src/renderer/lucide-icons.bundle.js');

esbuild.buildSync({
  entryPoints: [path.join(root, 'src/icons/lucide-entry.js')],
  outfile,
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: ['chrome120'],
  sourcemap: false,
  minify: false,
  legalComments: 'none',
  banner: { js: '/* Generated by scripts/build-icons.js — do not edit. */' },
  logLevel: 'info',
});

const size = require('fs').statSync(outfile).size;
console.log(`[icons] wrote ${path.relative(root, outfile)} (${(size / 1024).toFixed(0)} KB)`);
