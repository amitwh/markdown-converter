#!/usr/bin/env node
/**
 * Bundles the maxGraph flowchart editor into a single browser script for the
 * sandboxed standalone window (no Node integration, no module loader).
 */
const path = require('path');
const esbuild = require('esbuild');

const root = path.resolve(__dirname, '..');
const outfile = path.join(root, 'src/renderer/flowchart-editor.bundle.js');

esbuild.buildSync({
  entryPoints: [path.join(root, 'src/flowchart-editor/index.js')],
  outfile,
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: ['chrome120'],
  sourcemap: false,
  minify: false,
  legalComments: 'none',
  banner: {
    js: '/* Generated by scripts/build-flowchart-editor.js — do not edit. */',
  },
  logLevel: 'info',
});

const size = require('fs').statSync(outfile).size;
console.log(`[flowchart-editor] wrote ${path.relative(root, outfile)} (${(size / 1024).toFixed(0)} KB)`);
